"""Real mapped finite nodes, producer authority and atomic rejection."""
import os
from pathlib import Path
import subprocess
import sys


def files(root):
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def main():
    args = [Path(p).resolve() for p in sys.argv[1:]]
    c, java, cp, jp, cpub, jpub, cb, jb, fixture = args[:9]
    sources = dict(zip(["constants", "second", "middle", "root"], args[9:13], strict=True))
    metadata = dict(zip(sources, args[13:17], strict=True))
    mutants = args[17:]
    assert len(mutants) == 10
    deps = dict(constants=[], second=[], middle=["constants", "second"], root=["middle"])
    keys = {owner: "proof.finite.constant." + owner for owner in sources}
    originals = {p: p.read_bytes() for p in [fixture, *sources.values(), *metadata.values()]}
    work = Path(os.environ["TEST_TMPDIR"]) / "finite-source-ast"
    work.mkdir()
    scratch = work / "scratch"
    scratch.mkdir()

    def records(paths=None):
        paths = sources if paths is None else paths
        result = ["--root", keys["root"]]
        for owner in sources:
            result += ["--crate", owner, keys[owner], paths[owner],
                       sources[owner].name, metadata[owner]]
            for dep in deps[owner]:
                result += ["--dependency", dep, keys[dep]]
        return result

    def run(adapter, tail, accepted):
        result = subprocess.run([str(v) for v in [adapter, *tail]], capture_output=True,
                                text=True, timeout=120, env=dict(os.environ, TMPDIR=str(scratch)))
        assert (result.returncode == 0) == accepted, (adapter, result.stdout, result.stderr)
        assert not list(scratch.iterdir()) and not list(work.glob(".polyrust-stage-*"))
        assert originals == {p: p.read_bytes() for p in originals}
        return result

    for lang, production, probe, public, generated in [
        ("c", c, cp, cpub, cb), ("java", java, jp, jpub, jb),
    ]:
        output = work / lang
        observed = run(probe, ["--bundle", output, *records()], True)
        assert files(output) == files(generated), "read-only probes changed generated bytes"
        reads = [line for line in observed.stdout.splitlines() if line.startswith("CONSTANT_IMPORT_READ\t")]
        assert len(reads) == 23 and all("\tF64(" in line for line in reads), observed.stdout
        scalar = [line for line in observed.stderr.splitlines() if line.startswith("CONSTANT_AST\t")]
        local = [line for line in observed.stderr.splitlines() if line.startswith("LOCAL_CONSTANT_AST\t")]
        assert len(scalar) == 3 and len(local) == 2, observed.stderr
        assert all("\tF64(" in line for line in scalar + local)
        if lang == "java":
            assert "CONSTANT_IMPORT_GRAPH\tjava\t2" in observed.stdout
        single_results = []
        for label, adapter in [("production", production), ("public", public)]:
            directory = work / (lang + "-" + label)
            directory.mkdir()
            package = directory / ("package" if lang == "c" else "Generated.java")
            result = run(adapter, [fixture, package, "--package"], True)
            if label == "public":
                assert result.stdout.count("PUBLIC_CONSTANT_DECL\t") == 4, result.stdout
                assert result.stdout.count("PUBLIC_CONSTANT_READ\t") == 5, result.stdout
                assert "F64(" in result.stdout
            single_results.append(files(directory))
        assert single_results[0] == single_results[1]

    for index, adapter in enumerate(mutants):
        for existing in [False, True]:
            output = work / f"fault-{index}-{existing}"
            if existing:
                output.mkdir()
                (output / "sentinel").write_bytes(b"preserved\x00\xff")
            before = files(output) if existing else {}
            result = run(adapter, ["--bundle", output, *records()], False)
            assert "error[E" not in result.stderr
            expected = ["exact member certificate", "conflict", "owner", "authorit"] if index % 5 == 3 else ["identity/type/value differs"]
            if index < 5:
                # Conflicting opaque import handles may reject during registry
                # construction, before the value-mapping join is reached.
                expected.append("C declaration is already registered")
            assert any(marker in result.stderr for marker in expected), (index, result.stderr)
            assert output.exists() == existing
            if existing:
                assert files(output) == before

    altered = work / "changed.rs"
    altered.write_text(sources["constants"].read_text().replace(
        "pub const POSITIVE_ZERO: f64 = 0.0;", "pub const POSITIVE_ZERO: f64 = -0.0;"))
    assert altered.read_bytes() != sources["constants"].read_bytes()
    for lang, adapter in [("c", c), ("java", java)]:
        output = work / (lang + "-stale")
        result = run(adapter, ["--bundle", output, *records(dict(sources, constants=altered))], False)
        assert "metadata" in result.stderr and not output.exists(), result.stderr
    print("23 imported, 3 folded and 2 local finite mappings/target; 4 public declarations/5 reads; "
          "bit-exact authority mutations, preserved original bytes, stale metadata rejected")


if __name__ == "__main__":
    main()
