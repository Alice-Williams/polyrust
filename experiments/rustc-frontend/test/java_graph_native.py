by_name = {item["key"].split(".")[2]: identity for identity, item in by_id.items()}
methods = {(item["root"].split(":")[0], declaration["id"].split(":")[1]): declaration["target"]["path"]["member"] for item in manifests for declaration in item["declarations"] if declaration["kind"] == "function" and declaration["externally_reachable"]}
exports = {(item["root"].split(":")[0], binding["name"]): binding["target"]["id"].split(":")[1] for item in manifests for module in item["modules"] if module["id"] == item["root"] for binding in module["bindings"] if binding["target"]["kind"] == "declaration"}

runtimes = [path / "bin" for path in Path(os.environ["RUNFILES_DIR"]).iterdir()
            if "remotejdk21" in path.name and (path / "bin/javac").is_file()]
