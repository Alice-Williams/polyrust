#[derive(Serialize)]
pub struct JavaFileView {
    banner: String,
    package: String,
    imports: String,
    declarations: String,
}

impl ResolvedTemplateRenderer<JavaDialect> for JavaRenderer {
    type FileView = JavaFileView;

    fn target_name(&self) -> &'static str {
        "org.polyrust.java"
    }

    fn templates(&self) -> Vec<EmbeddedTemplate<JavaTemplateId>> {
        java_templates()
    }

    fn build_file_view(
        &self,
        _package: &LinkedTargetPackage<JavaDialect>,
        file: &LinkedFile<JavaDialect>,
        templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    ) -> Result<Self::FileView, Vec<Diagnostic>> {
        let banner = render_template(
            templates,
            JavaTemplateId::Comment,
            &CommentView {
                comment: "Generated by PolyRust from verified CoreIR.",
            },
            file,
        )?;
        let package = render_template(
            templates,
            JavaTemplateId::Package,
            &PackageView {
                name: file.module().name(),
            },
            file,
        )?;
        let mut imports = String::new();
        for import in file.imports() {
            imports.push_str(&render_template(
                templates,
                JavaTemplateId::Import,
                &ImportView {
                    path: import.kind().qualified_name(),
                },
                file,
            )?);
        }
        if !imports.is_empty() {
            imports.push('\n');
        }

        let declarations = if *file.placement() == JavaFilePlacement::Runtime {
            render_runtime_file(file, templates)?
        } else {
            let mut output = String::new();
            for item in file.items() {
                match &item.item {
                    JavaFileItem::Type { declaration, .. } => {
                        output.push_str(&render_type(
                            declaration,
                            &item.names,
                            0,
                            templates,
                            file,
                        )?);
                    }
                    JavaFileItem::RuntimeMembers { .. } => {
                        return Err(vec![render_diagnostic(
                            file,
                            "runtime member fragment appeared outside the runtime file",
                        )]);
                    }
                }
            }
            output
        };
        Ok(JavaFileView {
            banner,
            package,
            imports,
            declarations,
        })
    }
}

