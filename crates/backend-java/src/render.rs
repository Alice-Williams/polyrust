fn template(
    id: JavaTemplateId,
    source: &'static str,
    fields: &'static [&'static str],
) -> EmbeddedTemplate<JavaTemplateId> {
    EmbeddedTemplate::new(id, source, fields)
}

fn render_template<V: Serialize>(
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    id: JavaTemplateId,
    view: &V,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    templates.render(&id, view, "org.polyrust.java", file)
}

fn render_runtime_file(
    file: &LinkedFile<JavaDialect>,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
) -> Result<String, Vec<Diagnostic>> {
    let mut shell = None;
    let mut extra = String::new();
    for item in file.items() {
        match &item.item {
            JavaFileItem::Type { declaration, .. } => {
                if shell.replace((declaration, &item.names)).is_some() {
                    return Err(vec![render_diagnostic(
                        file,
                        "runtime file has multiple class shells",
                    )]);
                }
            }
            JavaFileItem::RuntimeMembers { members, .. } => {
                for member in members {
                    extra.push_str(&render_member(member, &item.names, 1, templates, file)?);
                }
            }
        }
    }
    let Some((shell, names)) = shell else {
        return Err(vec![render_diagnostic(
            file,
            "runtime file has no typed class shell",
        )]);
    };
    render_type_with_extra(shell, names, 0, &extra, templates, file)
}

fn render_diagnostic(file: &LinkedFile<JavaDialect>, message: &str) -> Diagnostic {
    Diagnostic::error(
        DiagnosticCode::InvalidStructure,
        message,
        file.source().clone(),
    )
}

