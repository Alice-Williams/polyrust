fn render_type(
    value: &JavaTypeDeclaration,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    render_type_with_extra(value, names, depth, "", templates, file)
}

fn render_type_with_extra(
    value: &JavaTypeDeclaration,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    extra_members: &str,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let indent = indent(depth);
    let visibility = visibility(value.visibility, true);
    let declaration_modifiers = modifiers(&value.modifiers);
    let type_parameters = render_type_parameters(&value.type_parameters);
    let declaration_name = match value.declared {
        Some(symbol) => resolved_name(
            names,
            &TargetSymbolRef::Generated(GeneratedSymbolId::Type(symbol)),
        )?,
        None => value.name.as_str().to_owned(),
    };
    let heritage = render_heritage(&value.heritage, names)?;
    let mut members = String::new();
    for member in &value.members {
        members.push_str(&render_member(member, names, depth + 1, templates, file)?);
    }
    members.push_str(extra_members);
    let components = value
        .record_components
        .iter()
        .map(|component| {
            Ok(format!(
                "{} {}",
                render_java_type(&component.ty, names)?,
                component.name.as_str()
            ))
        })
        .collect::<Result<Vec<_>, Vec<Diagnostic>>>()?
        .join(", ");
    let permits = value
        .permits
        .iter()
        .map(|ty| render_java_type(ty, names))
        .collect::<Result<Vec<_>, Vec<Diagnostic>>>()?
        .join(", ");
    match value.kind {
        JavaDeclarationKind::FinalClass => render_template(
            templates,
            JavaTemplateId::Class,
            &ClassView {
                indent: &indent,
                visibility,
                modifiers: &declaration_modifiers,
                name: &declaration_name,
                type_parameters: &type_parameters,
                heritage: &heritage,
                members: &members,
            },
            file,
        ),
        JavaDeclarationKind::Record => render_template(
            templates,
            JavaTemplateId::Record,
            &RecordView {
                indent: &indent,
                visibility,
                modifiers: &declaration_modifiers,
                name: &declaration_name,
                type_parameters: &type_parameters,
                components: &components,
                heritage: &heritage,
                members: &members,
            },
            file,
        ),
        JavaDeclarationKind::Interface => render_template(
            templates,
            JavaTemplateId::Interface,
            &InterfaceView {
                indent: &indent,
                visibility,
                modifiers: &declaration_modifiers,
                name: &declaration_name,
                type_parameters: &type_parameters,
                members: &members,
            },
            file,
        ),
        JavaDeclarationKind::SealedInterface => render_template(
            templates,
            JavaTemplateId::SealedInterface,
            &SealedInterfaceView {
                indent: &indent,
                visibility,
                modifiers: &declaration_modifiers,
                name: &declaration_name,
                type_parameters: &type_parameters,
                permits: &permits,
                members: &members,
            },
            file,
        ),
    }
}

fn render_member(
    value: &JavaMember,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    match value {
        JavaMember::Field(value) => render_field(value, names, depth, templates, file),
        JavaMember::CompileFailField(value) => {
            let field = JavaField {
                declared: None,
                modifiers: value.modifiers.clone(),
                ty: value.expected_type.clone(),
                name: value.name.clone(),
                initializer: Some(value.initializer.clone()),
            };
            render_field(&field, names, depth, templates, file)
        }
        JavaMember::Method(value) => render_method(value, names, depth, templates, file),
        JavaMember::Constructor(value) => render_constructor(value, names, depth, templates, file),
        JavaMember::NestedType(value) => render_type(value, names, depth, templates, file),
    }
}

fn render_field(
    value: &JavaField,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let indent = indent(depth);
    let modifiers = modifiers(&value.modifiers);
    let ty = render_java_type(&value.ty, names)?;
    let initializer = match &value.initializer {
        Some(value) => format!(" = {}", render_expr(value, names, templates, file)?),
        None => String::new(),
    };
    let field_name = match value.declared {
        Some(symbol) => resolved_name(
            names,
            &TargetSymbolRef::Generated(GeneratedSymbolId::Value(symbol)),
        )?,
        None => value.name.as_str().to_owned(),
    };
    render_template(
        templates,
        JavaTemplateId::Field,
        &FieldView {
            indent: &indent,
            modifiers: &modifiers,
            ty: &ty,
            name: &field_name,
            initializer: &initializer,
        },
        file,
    )
}

fn render_method(
    value: &JavaMethod,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let indent = indent(depth);
    let annotations = render_annotations(&value.annotations, depth, templates, file)?;
    let modifiers = modifiers(&value.modifiers);
    let type_parameters = render_method_type_parameters(&value.type_parameters);
    let return_type = render_java_type(&value.return_type, names)?;
    let parameters = render_parameters(&value.parameters, names, templates, file)?;
    let method_name = match value.declared {
        JavaMethodDeclaration::Callable(symbol) => resolved_name(
            names,
            &TargetSymbolRef::Generated(GeneratedSymbolId::Callable(symbol)),
        )?,
        JavaMethodDeclaration::Interface(symbol)
        | JavaMethodDeclaration::Implementation {
            interface: symbol, ..
        } => resolved_name(
            names,
            &TargetSymbolRef::Generated(GeneratedSymbolId::InterfaceMethod(symbol)),
        )?,
        JavaMethodDeclaration::Structural => value.name.as_str().to_owned(),
    };
    match &value.body {
        Some(body) => {
            let body = render_block(body, names, depth + 1, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::Method,
                &MethodView {
                    annotations: &annotations,
                    indent: &indent,
                    modifiers: &modifiers,
                    type_parameters: &type_parameters,
                    return_type: &return_type,
                    name: &method_name,
                    parameters: &parameters,
                    body: &body,
                },
                file,
            )
        }
        None => render_template(
            templates,
            JavaTemplateId::AbstractMethod,
            &AbstractMethodView {
                annotations: &annotations,
                indent: &indent,
                modifiers: &modifiers,
                type_parameters: &type_parameters,
                return_type: &return_type,
                name: &method_name,
                parameters: &parameters,
            },
            file,
        ),
    }
}

fn render_constructor(
    value: &JavaConstructor,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let indent = indent(depth);
    let modifiers = modifiers(&value.modifiers);
    let parameters = render_parameters(&value.parameters, names, templates, file)?;
    let body = render_block(&value.body, names, depth + 1, templates, file)?;
    render_template(
        templates,
        JavaTemplateId::Constructor,
        &ConstructorView {
            indent: &indent,
            modifiers: &modifiers,
            name: value.name.as_str(),
            parameters: &parameters,
            body: &body,
        },
        file,
    )
}

fn render_annotations(
    values: &[JavaAnnotation],
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let mut output = String::new();
    let indent = indent(depth);
    for value in values {
        let name = match value {
            JavaAnnotation::Override => "Override",
            JavaAnnotation::SafeVarargs => "SafeVarargs",
        };
        output.push_str(&render_template(
            templates,
            JavaTemplateId::Annotation,
            &AnnotationView {
                indent: &indent,
                name,
            },
            file,
        )?);
    }
    Ok(output)
}

fn render_parameters(
    values: &[JavaParameter],
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    values
        .iter()
        .map(|value| {
            let ty = render_java_type(&value.ty, names)?;
            render_template(
                templates,
                JavaTemplateId::Parameter,
                &ParameterView {
                    finality: if value.final_parameter { "final " } else { "" },
                    ty: &ty,
                    name: value.name.as_str(),
                },
                file,
            )
        })
        .collect::<Result<Vec<_>, Vec<Diagnostic>>>()
        .map(|values| values.join(", "))
}

