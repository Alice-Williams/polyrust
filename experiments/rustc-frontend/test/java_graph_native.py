"""Same four-crate Rust diamond, separate Java compilation, independent consumer."""
import os
import json
from pathlib import Path
import shutil
import subprocess
import sys
import java_manifest_assertions

probe, adapter, action_bundle, reference, seeds, *artifacts = [Path(value).resolve() for value in sys.argv[1:]]
work = Path(os.environ["TEST_TMPDIR"]) / "java-graph-native"
work.mkdir()
scratch = work / "scratch"
scratch.mkdir()
owners = ["leaf", "left", "right", "root"]
dependencies = {"leaf": [], "left": ["leaf"], "right": ["leaf"], "root": ["left", "right"]}
sources = {name: (artifacts[index * 2], artifacts[index * 2 + 1]) for index, name in enumerate(owners)}


def run(command, *, inputs=None, env=None):
    result = subprocess.run([str(arg) for arg in command], input=inputs, capture_output=True,
                            text=True, timeout=90, env=env)
    assert result.returncode == 0, (command, result.stdout, result.stderr)
    return result.stdout


def arguments(inputs, reverse=False):
    args = ["--root", "native.diamond.root.v1"]
    for name in reversed(owners) if reverse else owners:
        source, metadata = inputs[name]
        args += ["--crate", name, f"native.diamond.{name}.v1", source, source.name, metadata]
        for dependency in dependencies[name]:
            args += ["--dependency", dependency, f"native.diamond.{dependency}.v1"]
    return args


def generate(label, inputs, reverse=False, observe=False):
    output = work / label
    before = {path: path.read_bytes() for pair in inputs.values() for path in pair}
    command = [probe, "--check-crates"] if observe else [adapter, "--bundle", output]
    stdout = run([*command, *arguments(inputs, reverse)],
                 env=dict(os.environ, TMPDIR=str(scratch), POLYRUST_JAVA_GRAPH_PROBE=str(output)))
    assert stdout == ("certified 4 Java crates; no output published\n" if observe else "published 4 Java crates\n")
    assert not list(scratch.iterdir())
    assert before == {path: path.read_bytes() for pair in inputs.values() for path in pair}
    files = {str(path.relative_to(output)): path.read_bytes() for path in output.rglob("*") if path.is_file()}
    assert len(files) == (10 if observe else 9) and sum(name.endswith(".java") for name in files) == 4
    assert not list(work.glob(".polyrust-stage-*"))
    return output, files


original, expected_files = generate("original", sources)
observed, observation_files = generate("observed", sources, observe=True)
assert {name: data for name, data in observation_files.items() if name != "graph.probe"} == expected_files
assert {str(path.relative_to(action_bundle)): path.read_bytes() for path in action_bundle.rglob("*") if path.is_file()} == expected_files, "Bazel provider action differs from production CLI"
_, reordered = generate("reordered", sources, True)
assert reordered == expected_files, "graph record order changed source bytes"
relocation = work / "relocated-inputs"
relocation.mkdir()
relocated = {}
for name, pair in sources.items():
    directory = relocation / name
    directory.mkdir()
    moved = []
    for source in pair:
        target = directory / source.name
        shutil.copyfile(source, target)
        moved.append(target)
    relocated[name] = moved
_, moved = generate("relocated", relocated, True)
assert moved == expected_files, "physical relocation changed generated bytes or identities"

rows = [line.split("\t") for line in (observed / "graph.probe").read_text().splitlines()]
by_id = {row[1]: dict(root=row[2], key=bytes.fromhex(row[3]).decode(), path=row[4])
         for row in rows if row[0] == "OWNER"}
by_name = {item["key"].split(".")[2]: identity for identity, item in by_id.items()}
assert set(by_name) == set(owners)
assert [row[1] for row in rows if row[0] == "ROOT"] == [by_name["root"]]
actual_dependencies = {(row[1], row[2]) for row in rows if row[0] == "DEP"}
assert actual_dependencies == {(by_name[owner], by_name[dependency])
                               for owner, deps in dependencies.items() for dependency in deps}
methods = {(row[1], row[2]): row[3] for row in rows if row[0] == "FUNCTION"}
exports = {(row[1], bytes.fromhex(row[3]).decode()): row[4]
           for row in rows if row[0] == "EXPORT" and row[2] == by_id[row[1]]["root"]}


def call(owner, method, args):
    identity = by_name[owner]
    member = methods[identity, exports[identity, method]]
    return f"org.polyrust.generated.r{identity}.Generated.{member}({args})"


assert exports[by_name["leaf"], "score"] == exports[by_name["leaf"], "alias"]
assert exports[by_name["root"], "score"] == exports[by_name["root"], "alias"]
assert len(methods) == 14
index = json.loads((original / "bundle.json").read_text())
assert index["schema_version"] == 1 and index["target"] == "org.polyrust.java"
assert index["root"] == f'{by_name["root"]}:{by_id[by_name["root"]]["root"]}'
assert [member["root"] for member in index["members"]] == sorted(member["root"] for member in index["members"])
assert len(index["members"]) == 4
for member in index["members"]:
    identity, root_hash = member["root"].split(":")
    manifest = json.loads((original / member["manifest"]).read_text())
    assert manifest["schema_version"] == 1 and manifest["root"] == member["root"]
    assert manifest["source"] == member["source"] == by_id[identity]["path"]
    assert manifest["defining_key"] == by_id[identity]["key"]
    assert manifest["dependencies"] == sorted(f'{dep}:{by_id[dep]["root"]}' for own, dep in actual_dependencies if own == identity)
    declarations = {item["id"]: item for item in manifest["declarations"]}
    assert len(declarations) == len(manifest["declarations"])
    assert list(declarations) == sorted(declarations)
    public = {key.split(":")[1]: item for key, item in declarations.items() if item["kind"] == "function" and item["externally_reachable"]}
    assert {key: item["target"]["path"]["member"] for key, item in public.items()} == {key: method for (owner, key), method in methods.items() if owner == identity}
    for key, item in public.items():
        assert item["documentation"] == [bytes.fromhex(row[3]).decode() for row in rows if row[:3] == ["DOC", identity, key]]
        assert item["visibility"]["kind"] == "public"
        assert item["result"] in ("i32", "bool") and set(item["parameters"]) <= {"i32", "bool"}
    modules = {item["id"]: item for item in manifest["modules"]}
    assert len(modules) == len(manifest["modules"]) and list(modules) == sorted(modules)
    root_module = modules[member["root"]]
    assert root_module["parent"] is None
    assert {binding["name"]: binding["target"]["id"].split(":")[1] for binding in root_module["bindings"] if binding["target"]["kind"] == "declaration"} == {name: target for (owner, name), target in exports.items() if owner == identity}
    for item in declarations.values():
        assert item["module"] in modules
        if item["kind"] == "field":
            assert declarations[item["owner"]]["kind"] == "record" and item["scalar"] in ("i32", "bool")
            assert not item["externally_reachable"]
    private_methods = {item["target"]["path"]["member"] for item in declarations.values() if item["kind"] == "function" and not item["externally_reachable"]}
    assert {row[2] for row in rows if row[:2] == ["PRIVATE", identity]} <= private_methods
assert sum(row[0] == "PRIVATE" for row in rows) >= 1
docs = [bytes.fromhex(row[3]).decode() for row in rows if row[0] == "DOC"]
assert any("Public leaf score behind two aliases." in doc for doc in docs)
