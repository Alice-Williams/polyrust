        source = work / "PrivateRecord.java"
        source.write_text(f"final class PrivateRecord {{ {spelling} value; }}")
        result = subprocess.run([str(arg) for arg in [runtime / "javac", *flags, source]], capture_output=True, text=True, timeout=30)
        assert result.returncode != 0 and "private access" in result.stderr, result.stderr
