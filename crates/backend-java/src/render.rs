fn render_block(
    value: &JavaBlock,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let mut statements = String::new();
    for statement in &value.statements {
        statements.push_str(&render_stmt(statement, names, depth, templates, file)?);
    }
    render_template(
        templates,
        JavaTemplateId::Block,
        &BlockView {
            statements: &statements,
        },
        file,
    )
}

fn render_stmt(
    value: &JavaStmt,
    names: &std::collections::BTreeMap<TargetSymbolRef<JavaDialect>, JavaResolvedName>,
    depth: usize,
    templates: &mut CertifiedTemplateEngine<JavaTemplateId>,
    file: &LinkedFile<JavaDialect>,
) -> Result<String, Vec<Diagnostic>> {
    let indentation = indent(depth);
    match value {
        JavaStmt::Local {
            finality,
            ty,
            name,
            value,
        } => {
            let ty = render_java_type(ty, names)?;
            let initializer = match value {
                Some(value) => format!(" = {}", render_expr(value, names, templates, file)?),
                None => String::new(),
            };
            render_template(
                templates,
                JavaTemplateId::Local,
                &LocalView {
                    indent: &indentation,
                    finality: if *finality == JavaLocalFinality::Final {
                        "final "
                    } else {
                        ""
                    },
                    ty: &ty,
                    name: name.as_str(),
                    initializer: &initializer,
                },
                file,
            )
        }
        JavaStmt::Assign { target, value } => {
            let target = render_expr(target, names, templates, file)?;
            let value = render_expr(value, names, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::Assign,
                &AssignView {
                    indent: &indentation,
                    target: &target,
                    value: &value,
                },
                file,
            )
        }
        JavaStmt::Expression(value) => {
            let value = render_expr(value, names, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::ExpressionStatement,
                &ExpressionStatementView {
                    indent: &indentation,
                    value: &value,
                },
                file,
            )
        }
        JavaStmt::Return(value) => {
            let value = match value {
                Some(value) => format!(" {}", render_expr(value, names, templates, file)?),
                None => String::new(),
            };
            render_template(
                templates,
                JavaTemplateId::Return,
                &ReturnView {
                    indent: &indentation,
                    value: &value,
                },
                file,
            )
        }
        JavaStmt::If {
            condition,
            then_block,
            else_block,
        } => {
            let condition = render_expr(condition, names, templates, file)?;
            let then_body = render_block(then_block, names, depth + 1, templates, file)?;
            let else_body = match else_block {
                Some(value) => format!(
                    " else {{\n{}{}}}",
                    render_block(value, names, depth + 1, templates, file)?,
                    indentation
                ),
                None => String::new(),
            };
            render_template(
                templates,
                JavaTemplateId::If,
                &IfView {
                    indent: &indentation,
                    condition: &condition,
                    then_body: &then_body,
                    alternate_body: &else_body,
                },
                file,
            )
        }
        JavaStmt::ForEach {
            binding_type,
            binding,
            iterable,
            body,
        } => {
            let ty = render_java_type(binding_type, names)?;
            let iterable = render_expr(iterable, names, templates, file)?;
            let body = render_block(body, names, depth + 1, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::ForEach,
                &ForEachView {
                    indent: &indentation,
                    ty: &ty,
                    binding: binding.as_str(),
                    iterable: &iterable,
                    body: &body,
                },
                file,
            )
        }
        JavaStmt::While { condition, body } => {
            let condition = render_expr(condition, names, templates, file)?;
            let body = render_block(body, names, depth + 1, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::While,
                &WhileView {
                    indent: &indentation,
                    condition: &condition,
                    body: &body,
                },
                file,
            )
        }
        JavaStmt::Switch { value, arms } => {
            let value = render_expr(value, names, templates, file)?;
            let mut rendered_arms = String::new();
            for arm in arms {
                let pattern = match &arm.pattern {
                    JavaPattern::Default => "default".to_owned(),
                    JavaPattern::Literal(value) => render_literal(value),
                    JavaPattern::Type { ty, binding } => {
                        format!("case {} {}", render_java_type(ty, names)?, binding.as_str())
                    }
                };
                let body = render_block(&arm.body, names, depth + 2, templates, file)?;
                rendered_arms.push_str(&render_template(
                    templates,
                    JavaTemplateId::SwitchArm,
                    &SwitchArmView {
                        indent: &indent(depth + 1),
                        pattern: &pattern,
                        body: &body,
                    },
                    file,
                )?);
            }
            render_template(
                templates,
                JavaTemplateId::Switch,
                &SwitchView {
                    indent: &indentation,
                    value: &value,
                    arms: &rendered_arms,
                },
                file,
            )
        }
        JavaStmt::TryCatch { try_block, catches } => {
            let body = render_block(try_block, names, depth + 1, templates, file)?;
            let mut rendered_catches = String::new();
            for catch in catches {
                let exception_type = render_java_type(&catch.exception_type, names)?;
                let catch_body = render_block(&catch.body, names, depth + 1, templates, file)?;
                rendered_catches.push_str(&render_template(
                    templates,
                    JavaTemplateId::Catch,
                    &CatchView {
                        exception_type: &exception_type,
                        binding: catch.binding.as_str(),
                        body: &catch_body,
                        indent: &indentation,
                    },
                    file,
                )?);
            }
            render_template(
                templates,
                JavaTemplateId::TryCatch,
                &TryCatchView {
                    indent: &indentation,
                    body: &body,
                    catches: &rendered_catches,
                },
                file,
            )
        }
        JavaStmt::ThrowAssertion(message) => {
            let message = render_expr(message, names, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::Throw,
                &ThrowView {
                    indent: &indentation,
                    message: &message,
                },
                file,
            )
        }
        JavaStmt::Throw(value) => {
            let value = render_expr(value, names, templates, file)?;
            render_template(
                templates,
                JavaTemplateId::ThrowValue,
                &ExpressionStatementView {
                    indent: &indentation,
                    value: &value,
                },
                file,
            )
        }
        JavaStmt::Break => render_template(
            templates,
            JavaTemplateId::Break,
            &IndentView {
                indent: &indentation,
            },
            file,
        ),
        JavaStmt::Continue => render_template(
            templates,
            JavaTemplateId::Continue,
            &IndentView {
                indent: &indentation,
            },
            file,
        ),
    }
}

